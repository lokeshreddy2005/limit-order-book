// Benchmark harness for the OrderBook matching engine.
//
// Methodology (see README.md "Benchmark methodology" for the full writeup):
//   - Timing uses std::chrono::steady_clock, a monotonic high-resolution
//     clock unaffected by wall-clock adjustments, sampled immediately
//     before and after each individual operation under test.
//   - Every scenario runs a warm-up phase first (10% of its iteration
//     count, minimum 1000) whose operations are real and mutate real book
//     state, but whose latencies are *not* recorded, to let branch
//     predictors, the allocator, and OS page mappings reach steady state
//     before measurement begins.
//   - Reported numbers are mean, min, max, p50, p95, and p99 latency in
//     nanoseconds, computed by sorting the recorded sample set (see
//     benchmarks/Stats.hpp), plus overall throughput (operations / total
//     measured wall time) for the mixed workload.
//   - All scenarios use a fixed RNG seed (see below) so a re-run on the
//     same machine reproduces the same *sequence of operations*; absolute
//     timings will still vary run to run with normal system noise.
//
// This binary only ever prints numbers it just measured. Nothing here is
// hand-edited after the fact -- the README's benchmark section is a copy
// of real output from this program.

